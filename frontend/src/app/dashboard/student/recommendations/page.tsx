"use client";

import { DashboardLayout } from "@/components/DashboardLayout";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/Card";
import { Button } from "@/components/ui/Button";
import { CheckCircle, Clock, AlertTriangle, TrendingUp, Calendar, ChevronRight } from "lucide-react";
import { useState, useEffect } from "react";
import { motion } from "framer-motion";

export default function StudentRecommendationsPage() {
    const [recommendations, setRecommendations] = useState<any[]>([]);
    const [loading, setLoading] = useState(true);

    useEffect(() => {
        fetchRecommendations();
    }, []);

    const fetchRecommendations = async () => {
        try {
            const token = localStorage.getItem("token");
            const res = await fetch("http://localhost:5000/api/recommendations", {
                headers: { Authorization: `Bearer ${token}` }
            });
            const json = await res.json();
            if (json.success) {
                setRecommendations(json.data);
            }
        } catch (error) {
            console.error("Failed to load recommendations", error);
        } finally {
            setLoading(false);
        }
    };

    const markGoalCompleted = async (recId: string, goalId: string) => {
        // Logic to update goal status would go here
        alert("Goal marked as completed!");
    };

    return (
        <DashboardLayout role="student">
            <div className="flex flex-col gap-6">
                <div>
                    <h1 className="text-2xl font-bold tracking-tight">AI Academic Intervention Plan</h1>
                    <p className="text-muted-foreground mt-1 max-w-3xl">
                        Personalized goals and recommendations generated by our AI engine to help you succeed.
                    </p>
                </div>

                {loading ? (
                    <div className="flex justify-center py-10">
                        <div className="animate-spin h-8 w-8 border-4 border-primary border-t-transparent rounded-full"></div>
                    </div>
                ) : recommendations.length === 0 ? (
                    <Card className="border-border shadow-sm">
                        <CardContent className="flex flex-col items-center justify-center p-12 text-center text-muted-foreground">
                            <CheckCircle className="h-12 w-12 text-green-500 mb-4 opacity-50" />
                            <h3 className="text-lg font-bold text-foreground">No Active Intervention Plans</h3>
                            <p className="mt-2">Your performance is excellent, and you currently do not need an AI intervention plan. Keep up the great work!</p>
                        </CardContent>
                    </Card>
                ) : (
                    recommendations.map((rec) => (
                        <motion.div key={rec._id} initial={{ opacity: 0, y: 10 }} animate={{ opacity: 1, y: 0 }} className="space-y-6">
                            
                            {/* Current Plan Overview */}
                            <div className="grid grid-cols-1 md:grid-cols-4 gap-4">
                                <Card className="border-border shadow-sm md:col-span-3">
                                    <CardHeader className="pb-2">
                                        <div className="flex justify-between items-start">
                                            <div>
                                                <CardTitle className="text-xl flex items-center gap-2">
                                                    {rec.title}
                                                </CardTitle>
                                                <p className="text-sm text-muted-foreground mt-1">{rec.description}</p>
                                            </div>
                                            <span className={`px-3 py-1 rounded-full text-xs font-bold uppercase ${
                                                rec.riskLevel === 'High' ? 'bg-red-500/10 text-red-500' :
                                                rec.riskLevel === 'Medium' ? 'bg-amber-500/10 text-amber-500' :
                                                'bg-green-500/10 text-green-500'
                                            }`}>
                                                {rec.riskLevel} Risk
                                            </span>
                                        </div>
                                    </CardHeader>
                                    <CardContent>
                                        <div className="flex gap-6 mt-4">
                                            <div>
                                                <p className="text-xs text-muted-foreground uppercase font-bold tracking-wider mb-1">Status</p>
                                                <p className="text-sm font-semibold text-foreground flex items-center gap-1">
                                                    {rec.status === 'Completed' ? <CheckCircle className="w-4 h-4 text-green-500"/> : <Clock className="w-4 h-4 text-amber-500"/>}
                                                    {rec.status}
                                                </p>
                                            </div>
                                            <div>
                                                <p className="text-xs text-muted-foreground uppercase font-bold tracking-wider mb-1">Priority</p>
                                                <p className={`text-sm font-semibold flex items-center gap-1 ${rec.priority === 'Critical' ? 'text-red-500' : 'text-foreground'}`}>
                                                    {rec.priority === 'Critical' && <AlertTriangle className="w-4 h-4" />}
                                                    {rec.priority}
                                                </p>
                                            </div>
                                            <div>
                                                <p className="text-xs text-muted-foreground uppercase font-bold tracking-wider mb-1">Due Date</p>
                                                <p className="text-sm font-semibold text-foreground flex items-center gap-1">
                                                    <Calendar className="w-4 h-4 text-primary"/>
                                                    {new Date(rec.dueDate).toLocaleDateString()}
                                                </p>
                                            </div>
                                        </div>
                                    </CardContent>
                                </Card>

                                <Card className="border-border shadow-sm flex flex-col items-center justify-center p-6 bg-primary/5 border-primary/20">
                                    <TrendingUp className="h-8 w-8 text-primary mb-2" />
                                    <p className="text-xs font-bold uppercase tracking-wider text-muted-foreground">Improvement Score</p>
                                    <h3 className="text-4xl font-black text-primary mt-1">{rec.improvementScore}%</h3>
                                </Card>
                            </div>

                            {/* Goals */}
                            <Card className="border-border shadow-sm">
                                <CardHeader>
                                    <CardTitle className="text-lg flex items-center gap-2">
                                        <TrendingUp className="w-5 h-5 text-primary" /> Goal Breakdown
                                    </CardTitle>
                                </CardHeader>
                                <CardContent className="p-0">
                                    <div className="divide-y divide-border">
                                        {rec.goals.map((goal: any) => (
                                            <div key={goal._id} className="p-4 px-6 flex items-start gap-4 hover:bg-secondary/30 transition-colors">
                                                <div className={`mt-1 p-2 rounded-full ${goal.status === 'Completed' ? 'bg-green-500/10 text-green-500' : 'bg-primary/10 text-primary'}`}>
                                                    {goal.status === 'Completed' ? <CheckCircle className="w-4 h-4" /> : <Clock className="w-4 h-4" />}
                                                </div>
                                                <div className="flex-1">
                                                    <div className="flex items-center gap-2 mb-1">
                                                        <span className="text-xs font-bold uppercase tracking-wider px-2 py-0.5 rounded bg-secondary text-muted-foreground">{goal.type}</span>
                                                        <p className="font-semibold text-sm">{goal.title}</p>
                                                    </div>
                                                    <p className="text-sm text-muted-foreground">{goal.description}</p>
                                                </div>
                                                <div className="flex flex-col gap-2 items-end">
                                                    <span className={`text-xs font-bold ${goal.status === 'Completed' ? 'text-green-500' : 'text-amber-500'}`}>
                                                        {goal.status}
                                                    </span>
                                                    {goal.status !== 'Completed' && (
                                                        <Button variant="outline" size="sm" onClick={() => markGoalCompleted(rec._id, goal._id)} className="h-7 text-xs">
                                                            Mark Done <ChevronRight className="w-3 h-3 ml-1" />
                                                        </Button>
                                                    )}
                                                </div>
                                            </div>
                                        ))}
                                    </div>
                                </CardContent>
                            </Card>

                        </motion.div>
                    ))
                )}
            </div>
        </DashboardLayout>
    );
}
